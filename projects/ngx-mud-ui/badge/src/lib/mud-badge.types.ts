/** @description `numbered` shows the count; `dot` is a presence indicator. */
export type MudBadgeType = 'numbered' | 'dot';

/**
 * @description `default`, `brand`, `positive`, `warning`, `danger` are the official palette;
 * `dark`, `light`, `neutral`, `accent` are extra surfaces.
 */
export type MudBadgeVariant = 'default' | 'brand' | 'positive' | 'warning' | 'danger' | 'dark' | 'light' | 'neutral' | 'accent';

/** @description Five-step scale: `xs` 8px (dot only), `sm` 12px, `md` 16px, `lg` 20px, `xl` 24px. */
export type MudBadgeSize = 'xs' | 'sm' | 'md' | 'lg' | 'xl';
